// Pre-compute Lab for every swatch once.
const PANTONE_LAB = PANTONE.map((p) => ({ ...p, lab: rgbToLab(hexToRgb(p.hex)) }));

/** Nearest Pantone swatch to an { r, g, b } color, with a deltaE distance. */
export function nearestPantone(rgb) {
  if (!rgb) return null;
  const lab = rgbToLab(rgb);
  let best = null;
  let bestD = Infinity;
  for (const p of PANTONE_LAB) {
    const d = deltaE(lab, p.lab);
    if (d < bestD) { bestD = d; best = p; }
  }
  if (!best) return null;
  return { code: best.code, name: best.name, hex: best.hex, distance: Math.round(bestD * 10) / 10 };
}
